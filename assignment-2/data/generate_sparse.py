"""Generate the sparse benchmark inputs A and B for each (n, density).

Definitions used throughout the assignment:
    density  = percentage of NON-ZERO entries = 100 * nnz / n^2
    sparsity = percentage of ZERO entries     = 100 - density

Generation (per matrix, fresh numpy.random.default_rng(seed), PCG64):
    1. nnz = round(density/100 * n^2) exactly.
    2. nnz distinct flat positions drawn uniformly at random WITHOUT replacement
       from the n^2 cells (Generator.choice(..., replace=False)), then sorted.
    3. nnz values drawn uniform in [-1, 1); any value that is exactly 0.0 is
       redrawn, so every stored entry is a true non-zero.
Seeds: A 42, B 43 (the same seeds as the dense inputs).

Files written into the data directory (little-endian):
    {A,B}_n{n}_d{density}pct.csr   CSR binary:
        int64 n_rows, int64 n_cols, int64 nnz,
        int64 indptr[n_rows+1], int32 indices[nnz], float64 data[nnz]
    {A,B}_n{n}_d{density}pct.bin   (only when with_dense) the SAME logical
        matrix as raw row-major float64 n*n, no header (same format as the
        dense inputs), so dense and sparse methods multiply identical matrices.
    manifest.json                  generation parameters per (n, density).

Usage:
    .venv\\Scripts\\python data\\generate_sparse.py --sizes 1000 2000 --densities 0.1 1 5 --with-dense
"""

import argparse
import json
import os
from pathlib import Path

import numpy as np

DATA_DIR = Path(os.path.dirname(os.path.abspath(__file__))) / "sparse"
SEEDS = {"A": 42, "B": 43}
LOW, HIGH = -1.0, 1.0
MANIFEST = "manifest.json"


def density_tag(percent):
    """Compact textual form of a density percentage, used in file names."""
    return f"{float(percent):g}"


def target_nnz(n, percent):
    return int(round(float(percent) / 100.0 * n * n))


def csr_path(name, n, percent, data_dir=DATA_DIR):
    return Path(data_dir) / f"{name}_n{n}_d{density_tag(percent)}pct.csr"


def dense_path(name, n, percent, data_dir=DATA_DIR):
    return Path(data_dir) / f"{name}_n{n}_d{density_tag(percent)}pct.bin"


def manifest_key(n, percent):
    return f"n={n},density={density_tag(percent)}"


def generate_csr(seed, n, percent):
    """Return (indptr int64, indices int32, data float64) of one random matrix."""
    rng = np.random.default_rng(seed)
    nnz = target_nnz(n, percent)
    positions = rng.choice(n * n, size=nnz, replace=False, shuffle=False)
    positions = np.sort(positions.astype(np.int64))
    values = rng.uniform(LOW, HIGH, size=nnz)
    zeros = values == 0.0
    while zeros.any():
        values[zeros] = rng.uniform(LOW, HIGH, size=int(zeros.sum()))
        zeros = values == 0.0
    rows = positions // n
    indices = (positions % n).astype(np.int32)
    counts = np.bincount(rows, minlength=n).astype(np.int64)
    indptr = np.zeros(n + 1, dtype=np.int64)
    np.cumsum(counts, out=indptr[1:])
    return indptr, indices, values.astype(np.float64)


def write_csr(path, n, indptr, indices, data):
    with open(path, "wb") as handle:
        np.array([n, n, len(data)], dtype="<i8").tofile(handle)
        np.asarray(indptr, dtype="<i8").tofile(handle)
        np.asarray(indices, dtype="<i4").tofile(handle)
        np.asarray(data, dtype="<f8").tofile(handle)


def read_csr(path):
    """Return (n, indptr, indices, data) of a square CSR file."""
    with open(path, "rb") as handle:
        n_rows, n_cols, nnz = (int(v) for v in np.fromfile(handle, dtype="<i8", count=3))
        if n_rows != n_cols:
            raise ValueError(f"{path}: matrix is not square ({n_rows}x{n_cols})")
        indptr = np.fromfile(handle, dtype="<i8", count=n_rows + 1)
        indices = np.fromfile(handle, dtype="<i4", count=nnz)
        data = np.fromfile(handle, dtype="<f8", count=nnz)
    if len(data) != nnz or indptr[-1] != nnz:
        raise ValueError(f"{path}: truncated CSR file")
    return n_rows, indptr, indices, data


def csr_to_dense(n, indptr, indices, data):
    dense = np.zeros((n, n), dtype="<f8")
    rows = np.repeat(np.arange(n), np.diff(indptr))
    dense[rows, indices] = data
    return dense


def _expected_csr_bytes(n, nnz):
    return 3 * 8 + (n + 1) * 8 + nnz * 4 + nnz * 8


def _load_manifest(data_dir):
    path = Path(data_dir) / MANIFEST
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {
        "description": "Sparse inputs generated by data/generate_sparse.py",
        "generator": "numpy.random.default_rng(seed) (PCG64)",
        "numpy_version": np.__version__,
        "positions": "uniform without replacement over the n^2 cells "
                     "(Generator.choice, replace=False), sorted",
        "values": f"uniform [{LOW}, {HIGH}), exact 0.0 redrawn",
        "density_definition": "percentage of non-zero entries (100*nnz/n^2)",
        "sparsity_definition": "percentage of zero entries (100 - density)",
        "csr_format": "little-endian int64 n_rows, int64 n_cols, int64 nnz, "
                      "int64 indptr[n_rows+1], int32 indices[nnz], float64 data[nnz]",
        "dense_format": "little-endian float64 row-major n*n, no header",
        "entries": {},
    }


def ensure_sparse_inputs(n, percent, data_dir=DATA_DIR, with_dense=False, force=False):
    """Create the CSR (and optionally dense) files for A and B; update the manifest.

    Existing files of the expected size are reused unless force is set.
    Returns the manifest entry for (n, percent)."""
    data_dir = Path(data_dir)
    data_dir.mkdir(parents=True, exist_ok=True)
    nnz = target_nnz(n, percent)
    for name, seed in SEEDS.items():
        c_path = csr_path(name, n, percent, data_dir)
        d_path = dense_path(name, n, percent, data_dir)
        csr_ok = c_path.exists() and c_path.stat().st_size == _expected_csr_bytes(n, nnz)
        dense_ok = (not with_dense) or (d_path.exists() and d_path.stat().st_size == 8 * n * n)
        if not force and csr_ok and dense_ok:
            continue
        indptr, indices, data = generate_csr(seed, n, percent)
        write_csr(c_path, n, indptr, indices, data)
        if with_dense:
            csr_to_dense(n, indptr, indices, data).tofile(d_path)
    manifest = _load_manifest(data_dir)
    files = {name: csr_path(name, n, percent, data_dir).name for name in SEEDS}
    if with_dense:
        files.update({f"{name}_dense": dense_path(name, n, percent, data_dir).name
                      for name in SEEDS})
    entry = {
        "n": n,
        "density_percent": percent,
        "sparsity_percent": 100 - percent,
        "nnz_a": nnz,
        "nnz_b": nnz,
        "seeds": dict(SEEDS),
        "with_dense": bool(with_dense),
        "files": files,
    }
    manifest["entries"][manifest_key(n, percent)] = entry
    (data_dir / MANIFEST).write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return entry


def main():
    parser = argparse.ArgumentParser(description="Generate sparse benchmark inputs.")
    parser.add_argument("--sizes", type=int, nargs="+", required=True)
    parser.add_argument("--densities", type=float, nargs="+", required=True,
                        help="density percentages (non-zeros), e.g. 0.1 1 5")
    parser.add_argument("--with-dense", action="store_true",
                        help="also write the matching dense row-major files")
    parser.add_argument("--data-dir", default=str(DATA_DIR))
    parser.add_argument("--force", action="store_true", help="regenerate existing files")
    args = parser.parse_args()
    for n in args.sizes:
        for percent in args.densities:
            entry = ensure_sparse_inputs(n, percent, args.data_dir, args.with_dense, args.force)
            print(f"n={n} density={density_tag(percent)}% nnz={entry['nnz_a']}")


if __name__ == "__main__":
    main()
